//go:embed assets/*
var assetsFS embed.FS

var (
	moddwmapi                 = windows.NewLazySystemDLL("dwmapi.dll")
	procDwmSetWindowAttribute = moddwmapi.NewProc("DwmSetWindowAttribute")

	moduser32               = windows.NewLazySystemDLL("user32.dll")
	modkernel32             = windows.NewLazySystemDLL("kernel32.dll")
	modcomctl32             = windows.NewLazySystemDLL("comctl32.dll")
	procSendMessageW        = moduser32.NewProc("SendMessageW")
	procLoadIconW           = moduser32.NewProc("LoadIconW")
	procLoadImageW          = moduser32.NewProc("LoadImageW")
	procShowWindow          = moduser32.NewProc("ShowWindow")
	procSetForegroundWindow = moduser32.NewProc("SetForegroundWindow")
	procIsWindowVisible     = moduser32.NewProc("IsWindowVisible")
	procGetModuleHandleW    = modkernel32.NewProc("GetModuleHandleW")
	procSetWindowSubclass   = modcomctl32.NewProc("SetWindowSubclass")
	procDefSubclassProc     = modcomctl32.NewProc("DefSubclassProc")
)

const (
	WM_SETICON    = 0x0080
	WM_CLOSE      = 0x0010
	ICON_SMALL    = 0
	ICON_BIG      = 1
	SW_HIDE       = 0
	SW_SHOWNORMAL = 1
	SW_RESTORE    = 9
)

var activeGUIInstance *GUI

// guiSubclassProc intercepts native Win32 window messages such as WM_CLOSE
func guiSubclassProc(hwnd, msg, wParam, lParam, uIdSubclass, dwRefData uintptr) uintptr {
	if msg == WM_CLOSE {
		if activeGUIInstance != nil {
			activeGUIInstance.mu.Lock()
			onClose := activeGUIInstance.onClose
			activeGUIInstance.mu.Unlock()

			if onClose != nil {
				shouldHide := onClose()
				if shouldHide {
					procShowWindow.Call(hwnd, SW_HIDE)
					return 0 // Handled: prevent window destruction, keep running in tray!
				}
			}
		}
	}
	r, _, _ := procDefSubclassProc.Call(hwnd, msg, wParam, lParam)
	return r
}

// BridgeMessage represents an IPC message between JS and Go
type BridgeMessage struct {
	Action  string          `json:"action"`
	Payload json.RawMessage `json:"payload"`
}

// GUI encapsulates the WebView2 window and backend dispatchers
type GUI struct {
	window     webview2.WebView
	mu         sync.Mutex
	callbacks  map[string]func(payload json.RawMessage)
	eventQueue chan string
	isReady    bool
	title      string
	width      int
	height     int
	onClose    func() bool // returns true to hide to tray, false to allow window destruction
}

// NewGUI creates a new GUI instance
func NewGUI(title string, width, height int) *GUI {
	if width <= 0 {
		width = 920
	}
	if height <= 0 {
		height = 820
	}
	g := &GUI{
		callbacks:  make(map[string]func(payload json.RawMessage)),
		eventQueue: make(chan string, 100),
		title:      title,
		width:      width,
		height:     height,
	}
	activeGUIInstance = g
	return g
}

// On registers a handler for JS actions
func (g *GUI) On(action string, handler func(payload json.RawMessage)) {
	g.mu.Lock()
	defer g.mu.Unlock()
	g.callbacks[action] = handler
}

// Emit sends an event to the JS frontend safely
func (g *GUI) Emit(eventName string, data interface{}) {
	defer func() {
		_ = recover()
	}()

	dataBytes, err := json.Marshal(data)
	if err != nil {
		return
	}

	js := fmt.Sprintf("if (window.handleGoEvent) { window.handleGoEvent(%q, %s); }", eventName, string(dataBytes))

	g.mu.Lock()
	w := g.window
	g.mu.Unlock()

	if w == nil {
		return
	}

	w.Dispatch(func() {
		defer func() {
			_ = recover()
		}()

		g.mu.Lock()
		active := g.window
		g.mu.Unlock()

		if active != nil && active == w {
			w.Eval(js)
		}
	})
}

// SetOnClose sets a handler that determines whether the window should hide to system tray (return true) or exit (return false)
func (g *GUI) SetOnClose(handler func() bool) {
	g.mu.Lock()
	defer g.mu.Unlock()
	g.onClose = handler
}

// Log emits a log line to the frontend hydro-engineering log console and writes to persistent log file
func (g *GUI) Log(text string, tag string) {
	if tag == "" {
		tag = "БОБР"
	}
	log.Printf("[%s] %s", tag, text)
	g.Emit("log", map[string]string{
		"text": text,
		"tag":  tag,
	})
}

// Run launches the WebView2 window loop
func (g *GUI) Run() error {
	defer crash.Recover("GUI Run() event loop")

	activeGUIInstance = g

	appData := os.Getenv("LOCALAPPDATA")
	if appData == "" {
		home, _ := os.UserHomeDir()
		appData = filepath.Join(home, "AppData", "Local")
	}
	userDataPath := filepath.Join(appData, "BobrDobr", "WebView2")
	_ = os.MkdirAll(userDataPath, 0700)

	// In PE syso generated by rsrc, icon group resource ID is 2
	iconID := uint(2)

	// AutoFocus set to false: prevents WebView2 MoveFocus crash when window loses focus or user switches programs
	w := webview2.NewWithOptions(webview2.WebViewOptions{
		Debug:     false,
		AutoFocus: false,
		DataPath:  userDataPath,
		WindowOptions: webview2.WindowOptions{
			Title:  g.title,
			Width:  uint(g.width),
			Height: uint(g.height),
			IconId: iconID,
			Center: true,
		},
	})
	if w == nil {
		return fmt.Errorf("failed to create WebView2 window (ensure Microsoft Edge WebView2 is installed)")
	}
	defer func() {
		g.mu.Lock()
		g.window = nil
		activeGUIInstance = nil
		g.mu.Unlock()
		defer func() { _ = recover() }()
		w.Destroy()
	}()

	// Apply Windows 10/11 native Immersive Dark Mode to window titlebar and borders
	hwnd := uintptr(w.Window())
	if hwnd != 0 {
		// Subclass window to intercept native (X) button WM_CLOSE before webview2 destroys it
		if procSetWindowSubclass.Find() == nil {
			_, _, _ = procSetWindowSubclass.Call(
				hwnd,
				syscall.NewCallback(guiSubclassProc),
				1001,
				0,
			)
		}

		if procDwmSetWindowAttribute.Find() == nil {
			darkMode := int32(1)
			_, _, _ = procDwmSetWindowAttribute.Call(hwnd, 20, uintptr(unsafe.Pointer(&darkMode)), 4)
			_, _, _ = procDwmSetWindowAttribute.Call(hwnd, 19, uintptr(unsafe.Pointer(&darkMode)), 4)
		}

		// Explicitly set high-res icon and small titlebar icon on the HWND
		hInst, _, _ := procGetModuleHandleW.Call(0)
		var hIcon uintptr
		// Try resource ID 2 (rsrc generated), then ID 1
		for _, resID := range []uintptr{2, 1} {
			loaded, _, _ := procLoadImageW.Call(
				hInst,
				resID,
				1, // IMAGE_ICON
				32, 32,
				0x00008000, // LR_SHARED
			)
			if loaded != 0 {
				hIcon = loaded
				break
			}
			loaded, _, _ = procLoadIconW.Call(hInst, resID)
			if loaded != 0 {
				hIcon = loaded
				break
			}
		}

		if hIcon == 0 {
			exePath, _ := os.Executable()
			exeDir := filepath.Dir(exePath)
			candidates := []string{
				filepath.Join(exeDir, "assets", "bobr_logo.ico"),
				filepath.Join(exeDir, "bobr_logo.ico"),
				filepath.Join(exeDir, "..", "assets", "bobr_logo.ico"),
				"assets/bobr_logo.ico",
			}
			for _, c := range candidates {
				if _, err := os.Stat(c); err == nil {
					cPtr, _ := windows.UTF16PtrFromString(c)
					loaded, _, _ := procLoadImageW.Call(
						0,
						uintptr(unsafe.Pointer(cPtr)),
						1, // IMAGE_ICON
						32, 32,
						0x00000010|0x00000040, // LR_LOADFROMFILE | LR_DEFAULTSIZE
					)
					if loaded != 0 {
						hIcon = loaded
						break
					}
				}
			}
		}
		if hIcon != 0 {
			procSendMessageW.Call(hwnd, WM_SETICON, ICON_BIG, hIcon)
			procSendMessageW.Call(hwnd, WM_SETICON, ICON_SMALL, hIcon)
		}
	}

	w.SetSize(780, 580, webview2.HintMin)
	w.SetSize(g.width, g.height, webview2.HintNone)

	g.mu.Lock()
	g.window = w
	g.mu.Unlock()

	// Read embedded index.html
	htmlData, err := assetsFS.ReadFile("assets/index.html")
	if err != nil {
		return fmt.Errorf("failed to read embedded index.html: %w", err)
	}

	// Bind native IPC handler
	w.Bind("nativeBridgeCall", func(rawMsg string) {
		var msg BridgeMessage
		if err := json.Unmarshal([]byte(rawMsg), &msg); err != nil {
			log.Printf("[GUI] Invalid message from JS: %v", err)
			return
		}

		g.mu.Lock()
		handler, exists := g.callbacks[msg.Action]
		g.mu.Unlock()

		if exists && handler != nil {
			go func() {
				defer crash.Recover(fmt.Sprintf("IPC Action [%s]", msg.Action))
				handler(msg.Payload)
			}()
		}
	})

	w.SetHtml(string(htmlData))

	// Run main event loop
	w.Run()
	return nil
}

// Close closes the window
func (g *GUI) Close() {
	g.mu.Lock()
	w := g.window
	g.window = nil
	activeGUIInstance = nil
	g.mu.Unlock()

	if w != nil {
		defer func() { _ = recover() }()
		w.Dispatch(func() {
			defer func() { _ = recover() }()
			w.Destroy()
		})
	}
}

// Show makes the window visible and brings it to the foreground
func (g *GUI) Show() {
	defer func() { _ = recover() }()
	g.mu.Lock()
	w := g.window
	g.mu.Unlock()

	if w != nil {
		hwnd := uintptr(w.Window())
		if hwnd != 0 {
			procShowWindow.Call(hwnd, SW_RESTORE)
			procSetForegroundWindow.Call(hwnd)
		}
	}
}

// Hide hides the window to tray
func (g *GUI) Hide() {
	defer func() { _ = recover() }()
	g.mu.Lock()
	w := g.window
	g.mu.Unlock()

	if w != nil {
		hwnd := uintptr(w.Window())
		if hwnd != 0 {
			procShowWindow.Call(hwnd, SW_HIDE)
		}
	}
}

// ToggleVisibility shows or hides the window
func (g *GUI) ToggleVisibility() {
	defer func() { _ = recover() }()
	g.mu.Lock()
	w := g.window
	g.mu.Unlock()

	if w != nil {
		hwnd := uintptr(w.Window())
		if hwnd != 0 {
			visible, _, _ := procIsWindowVisible.Call(hwnd)
			if visible != 0 {
				procShowWindow.Call(hwnd, SW_HIDE)
			} else {
				procShowWindow.Call(hwnd, SW_RESTORE)
				procSetForegroundWindow.Call(hwnd)
			}
		}
	}
}

// IsVisible returns whether the window is currently visible
func (g *GUI) IsVisible() bool {
	defer func() { _ = recover() }()
	g.mu.Lock()
	w := g.window
	g.mu.Unlock()

	if w != nil {
		hwnd := uintptr(w.Window())
		if hwnd != 0 {
			v, _, _ := procIsWindowVisible.Call(hwnd)
			return v != 0
		}
	}
	return false
}
